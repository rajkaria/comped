"""upstream-pulse: the lockfile readers, and the judgements built on top of them.

Two things are being defended here. The first is that eight lockfile formats, written by eight
tools that agree on almost nothing, all come out the far side as the same four facts: name,
version, direct-or-transitive, production-or-dev. Every format gets a real file written to a real
temp tree, because a parser tested against a string someone wrote to make the test pass is not
tested at all.

The second is the architecture. This Play reports on public registries and does not open a socket:
the network half is a JSON partial another step writes, and this module reads it as data. If that
seam ever leaks — an `import urllib` added in a hurry — the whole claim these six Plays make about
the machine they run on goes with it, so it is asserted here as well as in the safety suite.
"""
