class TestHandWrittenReaders(unittest.TestCase):
    def test_the_yaml_reader_handles_the_shapes_lockfiles_use(self):
        doc = lockfiles.mini_yaml(
            "top: 1\n"
            "# a comment\n"
            "quoted: \"a: b\"\n"
            'flags: {a: 1, b: 2}\n'
            "nest:\n"
            "  inner: yes please\n"
            "  deeper:\n"
            "    leaf: true\n"
            "items:\n"
            "  - one\n"
            "  - two\n")
        self.assertEqual(doc["top"], "1")
        self.assertEqual(doc["quoted"], "a: b")
        self.assertEqual(doc["flags"], "{a: 1, b: 2}", "flow collections stay opaque on purpose")
        self.assertEqual(doc["nest"]["inner"], "yes please")
        self.assertTrue(doc["nest"]["deeper"]["leaf"])
        self.assertEqual(doc["items"], ["one", "two"])

    def test_the_toml_reader_handles_arrays_of_tables_and_inline_tables(self):
        doc = lockfiles.mini_toml(
            'version = 3\n'
            '# comment\n'
            'name = "with # hash"\n'
            '[[package]]\n'
            'name = "a"\n'
            'deps = [\n  "x",\n  "y",\n]\n'
            '[package.meta]\n'
            'kind = "lib"\n'
            '[[package]]\n'
            'name = "b"\n'
            '[table]\n'
            'inline = { version = "1.0", features = ["derive"] }\n')
        self.assertEqual(doc["version"], 3)
        self.assertEqual(doc["name"], "with # hash", "a hash inside a string is not a comment")
        self.assertEqual([p["name"] for p in doc["package"]], ["a", "b"])
        self.assertEqual(doc["package"][0]["deps"], ["x", "y"])
        self.assertEqual(doc["package"][0]["meta"]["kind"], "lib",
                         "a sub-table attaches to the last entry of the array above it")
        self.assertEqual(doc["table"]["inline"]["features"], ["derive"])

    def test_an_unreadable_lockfile_is_a_note_not_an_exception(self):
        result = lockfiles.parse("package-lock.json", "{not json at all")
        self.assertFalse(result["ok"])
        self.assertTrue(result["note"])
        self.assertEqual(lockfiles.resolve(result), [])

    def test_a_file_this_play_does_not_read_says_so(self):
        self.assertFalse(lockfiles.parse("composer.lock", "{}")["ok"])
        self.assertFalse(lockfiles.is_lockfile("composer.lock"))
        self.assertTrue(lockfiles.is_lockfile("requirements-test.txt"))


