class TestDormancyGrade(unittest.TestCase):
    def test_every_input_to_the_grade_is_printed_with_its_own_points(self):
        graded = upstream.score(_reg("left-pad", **ABANDONED), NOW, {})
        names = [s["signal"] for s in graded["signals"]]
        self.assertEqual(names, list(upstream.SIGNAL_ORDER),
                         "every input must appear, in a fixed order, every time")
        self.assertEqual(sum(s["points"] for s in graded["signals"]), graded["points"],
                         "the printed inputs must add up to the printed score")
        self.assertEqual(sum(s["max"] for s in graded["signals"]), graded["max_points"])
        for s in graded["signals"]:
            self.assertTrue(s["value"], "{0} printed no reading".format(s["signal"]))
            self.assertTrue(s["why"], "{0} printed no scoring rule".format(s["signal"]))
            self.assertLessEqual(s["points"], s["max"])
        self.assertIn(graded["grade"], ("D", "F"))
        self.assertTrue(graded["dormant"])
        self.assertTrue(graded["single_maintainer"])

    def test_a_healthy_package_grades_a_and_still_prints_all_seven_inputs(self):
        graded = upstream.score(_reg("well-kept"), NOW, {})
        self.assertEqual(graded["grade"], "A")
        self.assertEqual(len(graded["signals"]), len(upstream.SIGNAL_ORDER))
        self.assertFalse(graded["dormant"])
