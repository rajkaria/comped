def _write_tree(root: Path):
    for rel, body in sorted(TREE.items()):
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(str(path), "w", encoding="utf-8") as fh:
            fh.write(body)
    return root


def _flat(card: str) -> str:
    """The card as one line of prose: box drawing gone, wrapped rows rejoined."""
    rows = [line.strip("\u2502\u250c\u2510\u2514\u2518\u251c\u2524\u2500 ")
            for line in card.splitlines()]
    return " ".join(" ".join(rows).split())


def _index(records):
    """{(lockfile, name): record} — every assertion below is about one row of one file."""
    return dict(((r["lockfile"], r["name"]), r) for r in records if r.get("kind") == "dep")


class LockfileTree(unittest.TestCase):
    """One temp tree, read once, then asserted format by format."""

    @classmethod
    def setUpClass(cls):
        cls._tmp = tempfile.TemporaryDirectory()
        cls.root = _write_tree(Path(cls._tmp.name))
        cls.sources, cls.records = upstream.read_source(
            "lockfiles", Budget(), {"root": str(cls.root)})
        cls.by = _index(cls.records)

    @classmethod
    def tearDownClass(cls):
        cls._tmp.cleanup()

    def kind(self, lockfile, name):
        row = self.by.get((lockfile, name))
        self.assertIsNotNone(row, "{0} is missing from {1}".format(name, lockfile))
        return (row["direct"], row["scope"])


