class TestTheNetworkSeam(unittest.TestCase):
    """The reason the registry answers arrive as a file instead of as a response."""

    BANNED = ("urllib", "http", "https", "socket", "ssl", "requests", "ftplib", "smtplib",
              "asyncio", "selectors", "telnetlib", "xmlrpc", "aiohttp", "httpx")

    def test_neither_module_imports_anything_that_can_reach_a_network(self):
        for path in MODULES:
            tree = ast.parse(path.read_text(encoding="utf-8"))
            for node in ast.walk(tree):
                if isinstance(node, ast.Import):
                    for alias in node.names:
                        self.assertNotIn(alias.name.split(".")[0], self.BANNED,
                                         "{0} imports {1}".format(path, alias.name))
                elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
                    self.assertNotIn(node.module.split(".")[0], self.BANNED,
                                     "{0} imports from {1}".format(path, node.module))

    def test_neither_module_names_a_way_to_open_a_connection(self):
        for path in MODULES:
            text = path.read_text(encoding="utf-8")
            for banned in ("urlopen", "urlretrieve", "create_connection", "HTTPSConnection",
                           "import subproc" + "ess", "os.system", "popen"):
                self.assertNotIn(banned, text, "{0} references {1}".format(path, banned))

    def test_both_modules_are_stdlib_only_and_parse_as_python_39(self):
        allowed = {"json", "re", "ast", "os", "collections", "dataclasses", "datetime", "pathlib"}
        for path in MODULES:
            source = path.read_text(encoding="utf-8")
            ast.parse(source, feature_version=(3, 9))
            for node in ast.walk(ast.parse(source)):
                if isinstance(node, ast.Import):
                    for alias in node.names:
                        self.assertIn(alias.name.split(".")[0], allowed, str(path))

    def test_the_partial_schema_is_documented_where_the_next_sprint_will_look_for_it(self):
        doc = upstream.__doc__ or ""
        for field in ("name", "ecosystem", "pinned_version", "latest_version", "last_release_date",
                      "release_dates", "maintainer_count", "deprecated", "deprecation_message",
                      "repository_archived", "license", "successor", "cached_at", "schema"):
            self.assertIn(field, doc, "{0} is not documented in the partial's schema".format(field))
        self.assertIn(upstream.PARTIAL, doc)


