def _dep(name, ecosystem="npm", version="1.0.0", direct=True, scope="production", depth=0,
         path=None, lockfile="package-lock.json", local=False):
    return {"kind": "dep", "name": name, "display": name, "ecosystem": ecosystem,
            "version": version, "direct": direct, "scope": scope, "depth": depth,
            "path": path or [name], "local": local, "lockfile": lockfile,
            "format": "package-lock.json (lockfileVersion 3)",
            "direct_basis": "the package.json next to it"}


def _reg(name, ecosystem="npm", **kw):
    entry = {"kind": "registry", "name": name, "ecosystem": ecosystem,
             "pinned_version": "1.0.0", "latest_version": "1.0.0",
             "last_release_date": "2026-08-01T00:00:00Z",
             "release_dates": ["2026-02-01T00:00:00Z", "2026-08-01T00:00:00Z",
                               "2025-06-01T00:00:00Z"],
             "maintainer_count": 5, "deprecated": False, "deprecation_message": "",
             "repository_archived": False, "license": "MIT", "pinned_license": "MIT",
             "successor": "", "error": ""}
    entry.update(kw)
    return entry


def _meta(cached_at="2026-09-05T09:00:00Z", **kw):
    doc = {"kind": "registry_meta", "cached_at": cached_at, "source": "registry.npmjs.org",
           "requested": 0, "returned": 0}
    doc.update(kw)
    return doc


